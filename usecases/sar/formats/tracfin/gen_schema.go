//go:build ignore

// gen_schema writes schema_gen.go, the Go description of the TRACFIN
// "financier" format, from the verified TRACFIN catalog (manifest, CSV code
// lists with labels, XSD facets). Run once per published TRACFIN version:
//
//	go run usecases/sar/formats/tracfin/gen_schema.go > usecases/sar/formats/tracfin/schema_gen.go
package main

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/checkmarble/marble-backend/usecases/tracfin"
)

func q(s string) string { return strconv.Quote(s) }

func pattern(p string) string {
	p = strings.TrimSuffix(strings.TrimPrefix(p, "^"), "$")
	p = strings.ReplaceAll(p, `[\w-\._]`, `[\w\-._]`)
	p = strings.ReplaceAll(p, `[\w-]`, `[\w\-]`)
	if _, err := regexp.Compile(p); err != nil {
		fmt.Fprintln(os.Stderr, "pattern", p, err)
		os.Exit(1)
	}
	return p
}

func label(f tracfin.Field) string {
	doc := strings.TrimSpace(f.Documentation)
	if doc == "" && f.Kind == "block" {
		doc = strings.TrimSpace(f.TypeDocumentation)
	}
	doc = strings.TrimPrefix(doc, "Section : ")
	if i := strings.IndexAny(doc, "\n\r"); i >= 0 {
		doc = strings.TrimSpace(doc[:i])
	}
	if doc == "" || len(doc) > 80 || strings.HasPrefix(doc, "Ref:") {
		return f.Name
	}
	return doc
}

func main() {
	c, err := tracfin.LoadCatalog()
	if err != nil {
		panic(err)
	}
	children := map[string][]tracfin.Field{}
	hasAttr := map[string]bool{}
	for _, id := range c.OrderedFields {
		f := c.Fields[id]
		if f.Parent == "" {
			continue
		}
		children[f.Parent] = append(children[f.Parent], f)
		if f.Attribute {
			hasAttr[f.Parent] = true
		}
	}
	type simple struct {
		base              string
		minL, maxL, total int
		pat, list         string
	}
	simples := map[string]simple{}
	lists := map[string][][2]string{}
	simpleOf := func(f tracfin.Field) string {
		s := simple{base: "BaseString", minL: -1, maxL: -1, total: -1}
		switch f.ValueKind {
		case "boolean":
			s.base = "BaseBoolean"
		case "decimal":
			s.base = "BaseDecimal"
		}
		var enums []string
		for _, k := range f.Constraints {
			n, _ := strconv.Atoi(k.Value)
			switch k.Kind {
			case "minLength":
				s.minL = n
			case "maxLength":
				s.maxL = n
			case "totalDigits":
				s.total = n
				if s.base == "BaseString" {
					s.base = "BaseInt"
				}
			case "pattern":
				s.pat = pattern(k.Value)
			case "enumeration":
				enums = append(enums, k.Value)
			}
		}
		if len(f.Catalogs) > 0 {
			name := strings.Join(f.Catalogs, "+")
			if _, ok := lists[name]; !ok {
				var codes [][2]string
				for _, cat := range f.Catalogs {
					for _, code := range c.Codes[cat] {
						codes = append(codes, [2]string{code.Value, code.Label})
					}
				}
				if len(codes) > 0 {
					lists[name] = codes
				}
			}
			if _, ok := lists[name]; ok {
				s.list = name
			}
		}
		if s.list == "" && len(enums) > 0 {
			var codes [][2]string
			for _, e := range enums {
				codes = append(codes, [2]string{e, e})
			}
			lists[f.ID] = codes
			s.list = f.ID
		}
		simples[f.ID] = s
		return f.ID
	}
	type elem struct {
		name, typ, choice string
		min, max          int
		attr              bool
		label, doc        string
	}
	type complexT struct {
		text  string
		label string
		elems []elem
	}
	complexes := map[string]*complexT{}
	card := func(f tracfin.Field) (int, int) {
		mn, _ := strconv.Atoi(f.Min)
		mx := -1
		if f.Max != "unbounded" {
			mx, _ = strconv.Atoi(f.Max)
		}
		if f.Coverage == "excluded" {
			mn, mx = 0, 0
		}
		return mn, mx
	}
	var build func(f tracfin.Field) string
	build = func(f tracfin.Field) string {
		if f.Kind != "block" && !hasAttr[f.ID] {
			return simpleOf(f)
		}
		t := &complexT{label: label(f)}
		if f.Kind != "block" {
			t.text = simpleOf(f)
		}
		complexes[f.ID] = t
		for _, ch := range children[f.ID] {
			mn, mx := card(ch)
			t.elems = append(t.elems, elem{name: ch.Name, typ: build(ch), choice: ch.Choice, min: mn, max: mx, attr: ch.Attribute, label: label(ch), doc: strings.Join(strings.Fields(ch.Documentation), " ")})
		}
		return f.ID
	}
	build(c.Fields["/ds"])
	w := os.Stdout
	fmt.Fprintln(w, "// Code generated by usecases/sar/formats/tracfin/gen_schema.go from the TRACFIN financier catalog. DO NOT EDIT.")
	fmt.Fprintf(w, "// Source: %s (catalog %s).\n\npackage tracfin\n\nimport . \"github.com/checkmarble/marble-backend/usecases/sar/format\"\n\n", c.SourceVersion, c.Version)
	fmt.Fprintln(w, "func generatedSchema() *Schema {\n\treturn &Schema{")
	fmt.Fprintln(w, "\t\tKey: Key, Label: \"TRACFIN déclaration de soupçon, module financier\", RootElement: \"ds\", RootType: \"/ds\",")
	fmt.Fprintln(w, "\t\tComplex: map[string]*ComplexType{")
	names := make([]string, 0, len(complexes))
	for n := range complexes {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		t := complexes[n]
		fmt.Fprintf(w, "\t\t\t%s: {Name: %s, Label: %s, Text: %s, Elements: []Element{\n", q(n), q(n), q(t.label), q(t.text))
		choices := map[string]bool{}
		var order []string
		for _, e := range t.elems {
			fmt.Fprintf(w, "\t\t\t\t{Name: %s, Label: %s, Type: %s, Min: %d, Max: %d, Attribute: %v, Choice: %s, Doc: %s},\n", q(e.name), q(e.label), q(e.typ), e.min, e.max, e.attr, q(e.choice), q(e.doc))
			if e.choice != "" && !choices[e.choice] {
				choices[e.choice] = true
				order = append(order, e.choice)
			}
		}
		fmt.Fprintln(w, "\t\t\t}, Choices: []Choice{")
		for _, id := range order {
			var leads []string
			for _, e := range t.elems {
				if e.choice == id {
					leads = append(leads, q(e.name))
				}
			}
			mn := 0
			for _, ch := range c.Choices {
				if ch.ID == id {
					mn, _ = strconv.Atoi(ch.Min)
				}
			}
			fmt.Fprintf(w, "\t\t\t\t{ID: %s, Min: %d, Leads: []string{%s}},\n", q(id), mn, strings.Join(leads, ", "))
		}
		fmt.Fprintln(w, "\t\t\t}},")
	}
	fmt.Fprintln(w, "\t\t},\n\t\tSimple: map[string]*SimpleType{")
	names = names[:0]
	for n := range simples {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		s := simples[n]
		fmt.Fprintf(w, "\t\t\t%s: {Name: %s, Base: %s, MinLength: %d, MaxLength: %d, Pattern: %s, TotalDigits: %d, FractionDigits: -1, CodeList: %s},\n", q(n), q(n), s.base, s.minL, s.maxL, q(s.pat), s.total, q(s.list))
	}
	fmt.Fprintln(w, "\t\t},\n\t\tCodeLists: map[string]*CodeList{")
	names = names[:0]
	for n := range lists {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(w, "\t\t\t%s: {Name: %s, Source: \"TRACFIN référentiels\", Codes: []Code{\n", q(n), q(n))
		for _, code := range lists[n] {
			fmt.Fprintf(w, "\t\t\t\t{Value: %s, Label: %s},\n", q(code[0]), q(code[1]))
		}
		fmt.Fprintln(w, "\t\t\t}},")
	}
	fmt.Fprintln(w, "\t\t},\n\t}\n}")
}
